import { expect, test } from '@playwright/test'
import { login, logout } from './helpers'

test('creates, edits and removes wallets without leaking them between users', async ({ page }) => {
  await login(page)
  await page.goto('/account/wallets')
  await page.locator('section').getByRole('button', { name: 'Add wallet' }).click()
  const form = page.locator('form')
  await form.getByLabel('Label').fill('Ada E2E wallet')
  await form.getByLabel('Address').fill('0xADAE2E')
  await form.getByLabel('Network').selectOption('polygon')
  await form.getByRole('button', { name: 'Add wallet' }).click()
  let wallet = page.locator('.wallet-row').filter({ hasText: 'Ada E2E wallet' })
  await expect(wallet).toBeVisible()
  await wallet.getByRole('button', { name: 'Edit' }).click()
  await form.getByLabel('Label').fill('Ada isolated wallet')
  await form.getByRole('button', { name: 'Save wallet' }).click()
  wallet = page.locator('.wallet-row').filter({ hasText: 'Ada isolated wallet' })
  await expect(wallet).toBeVisible()

  await logout(page)
  await login(page, 'alan')
  await page.goto('/account/wallets')
  await expect(page.getByText('Ada isolated wallet')).toHaveCount(0)
  await expect(page.getByText('Alan primary')).toBeVisible()

  await logout(page)
  await login(page)
  await page.goto('/account/wallets')
  wallet = page.locator('.wallet-row').filter({ hasText: 'Ada isolated wallet' })
  page.once('dialog', (dialog) => dialog.accept())
  await wallet.getByRole('button', { name: 'Remove' }).click()
  await expect(wallet).toHaveCount(0)
})

test('completes checkout, restores the order, and blocks removal of its wallet', async ({ page }) => {
  await login(page)
  await page.goto('/nft/nft-1')
  await page.getByRole('button', { name: 'Buy now' }).click()
  await expect(page.getByRole('heading', { name: 'Shopping cart' })).toBeVisible()
  await page.getByRole('link', { name: 'Continue to checkout' }).click()
  await page.getByRole('button', { name: 'Connect wallet' }).click()
  await expect(page.getByText('Connected to ethereum.')).toBeVisible()
  await page.getByRole('button', { name: 'Confirm purchase' }).click()
  await expect(page.getByRole('heading', { name: 'Purchase confirmed' })).toBeVisible()
  const orderUrl = page.url()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Purchase confirmed' })).toBeVisible()

  await page.goto('/account/wallets')
  const wallet = page.locator('.wallet-row').filter({ hasText: 'Ada primary' })
  page.once('dialog', (dialog) => dialog.accept())
  await wallet.getByRole('button', { name: 'Remove' }).click()
  await expect(page.getByRole('alert')).toContainText('referenced by an existing order')
  await page.goto(orderUrl)
  await expect(page.getByRole('heading', { name: 'Purchase confirmed' })).toBeVisible()
})
