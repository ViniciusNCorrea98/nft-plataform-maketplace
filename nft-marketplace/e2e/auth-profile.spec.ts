import { expect, test } from '@playwright/test'
import { login, logout } from './helpers'

test('restores the session on reload, logs out, and protects private routes', async ({ page }) => {
  await page.goto('/cart')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByLabel('Email').fill('ada@example.test')
  await page.getByLabel('Password').fill('demo-password')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page).toHaveURL(/\/cart$/)

  await page.reload()
  await expect(page.getByRole('heading', { name: 'Shopping cart' })).toBeVisible()
  await logout(page)
  await page.goto('/account/profile')
  await expect(page).toHaveURL(/\/login\?redirect=/)
})

test('edits profile/avatar and changes password only for the current mock runtime', async ({ page }) => {
  await login(page)
  await page.goto('/account/profile')
  await page.getByLabel('Name').fill('Ada E2E')
  await page.getByLabel('Bio').fill('Persisted by Playwright')
  await page.getByLabel('Avatar URL').fill('http://127.0.0.1:4173/src/assets/nftTwo.webp')
  await page.getByRole('button', { name: 'Save profile' }).click()
  await expect(page.getByText('Profile updated.')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Name')).toHaveValue('Ada E2E')
  await expect(page.getByLabel('Bio')).toHaveValue('Persisted by Playwright')
  await expect(page.getByAltText("Ada E2E's avatar")).toBeVisible()

  await page.getByLabel('Current password').fill('wrong-password')
  await page.getByLabel('New password').fill('e2e-password')
  await page.getByRole('button', { name: 'Change password' }).click()
  await expect(page.getByRole('alert')).toContainText('Current password is incorrect')
  await expect(page.getByRole('heading', { name: 'Profile', level: 1 })).toBeVisible()

  await page.getByLabel('Current password').fill('demo-password')
  await page.getByLabel('New password').fill('e2e-password')
  await page.getByRole('button', { name: 'Change password' }).click()
  await expect(page.getByText('Password changed.')).toBeVisible()
  await logout(page)
  await page.getByRole('link', { name: 'Connect wallet' }).click()
  await page.getByLabel('Email').fill('ada@example.test')
  await page.getByLabel('Password').fill('e2e-password')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()

  await page.reload()
  await logout(page)
  await page.getByRole('link', { name: 'Connect wallet' }).click()
  await page.getByLabel('Email').fill('ada@example.test')
  await page.getByLabel('Password').fill('e2e-password')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('alert')).toContainText('Invalid credentials')
  await page.getByLabel('Password').fill('demo-password')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()
})

test('clearing persisted state removes the session and restores fixture credentials', async ({ page }) => {
  await login(page)
  await page.goto('/account/profile')
  await page.getByLabel('Current password').fill('demo-password')
  await page.getByLabel('New password').fill('temporary-password')
  await page.getByRole('button', { name: 'Change password' }).click()
  await expect(page.getByText('Password changed.')).toBeVisible()

  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByLabel('Email').fill('ada@example.test')
  await page.getByLabel('Password').fill('demo-password')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page).toHaveURL(/\/account\/profile$/)
})
